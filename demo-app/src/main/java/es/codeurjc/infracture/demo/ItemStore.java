package es.codeurjc.infracture.demo;

import java.time.Instant;
import java.util.Optional;
import org.springframework.boot.autoconfigure.condition.ConditionalOnProperty;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.stereotype.Repository;
import org.springframework.transaction.annotation.Transactional;

// The items of DATABASE_CRUD in the experiment's PostgreSQL. Several services may share one database, so
// creating the table and the 100 fixed items is idempotent and serialized by a lock of the database itself.
@Repository
@ConditionalOnProperty(name = "APP_MODE", havingValue = "DATABASE_CRUD")
public class ItemStore {

    public static final int INITIAL_ITEMS = 100;
    // Any constant works; every demo-app sharing the database uses the same one.
    private static final long INITIALIZATION_LOCK = 97;

    private final JdbcClient jdbc;

    public ItemStore(JdbcClient jdbc) {
        this.jdbc = jdbc;
    }

    // Created ids start after the fixed items, so a new item never takes the id of a fixed one.
    @Transactional
    public void initialize() {
        jdbc.sql("SELECT pg_advisory_xact_lock(?)").param(INITIALIZATION_LOCK).query().singleRow();
        jdbc.sql("""
                CREATE TABLE IF NOT EXISTS items (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 101) PRIMARY KEY,
                    name VARCHAR(100) NOT NULL,
                    quantity INTEGER NOT NULL CHECK (quantity BETWEEN 0 AND 1000000),
                    version INTEGER NOT NULL,
                    updated_at TIMESTAMP WITH TIME ZONE NOT NULL)
                """).update();
        jdbc.sql("""
                INSERT INTO items (id, name, quantity, version, updated_at)
                SELECT n, 'item-' || lpad(n::text, 3, '0'), n * 10, 1, now() FROM generate_series(1, ?) AS n
                ON CONFLICT (id) DO NOTHING
                """).param(INITIAL_ITEMS).update();
    }

    public long count() {
        return jdbc.sql("SELECT count(*) FROM items").query(Long.class).single();
    }

    public Optional<Item> find(long id) {
        return jdbc.sql("SELECT id, name, quantity, version, updated_at FROM items WHERE id = ?").param(id)
                .query(Item.class).optional();
    }

    public Item create(String name, int quantity) {
        return jdbc.sql("""
                INSERT INTO items (name, quantity, version, updated_at) VALUES (?, ?, 1, now())
                RETURNING id, name, quantity, version, updated_at
                """).params(name, quantity).query(Item.class).single();
    }

    // Each update raises the version, so a read shows how many times the item changed.
    public Optional<Item> update(long id, String name, int quantity) {
        return jdbc.sql("""
                UPDATE items SET name = ?, quantity = ?, version = version + 1, updated_at = now() WHERE id = ?
                RETURNING id, name, quantity, version, updated_at
                """).params(name, quantity, id).query(Item.class).optional();
    }

    public record Item(long id, String name, int quantity, int version, Instant updatedAt) {
    }
}
