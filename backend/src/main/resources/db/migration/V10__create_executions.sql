-- An execution runs one exact revision of a scenario (ADR 0004). Its rows keep a copy of what ran,
-- so later edits to the scenario do not change the history.
CREATE TABLE executions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    scenario_id BIGINT NOT NULL,
    scenario_revision INTEGER NOT NULL,
    phase VARCHAR(20) NOT NULL,
    stop_cause VARCHAR(20),
    outcome VARCHAR(20),
    failure_reason VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    released_at TIMESTAMP WITH TIME ZONE,

    CONSTRAINT pk_executions
        PRIMARY KEY (id),

    CONSTRAINT fk_executions_scenario
        FOREIGN KEY (scenario_id) REFERENCES scenarios (id),

    CONSTRAINT ck_executions_revision_positive
        CHECK (scenario_revision >= 1),

    CONSTRAINT ck_executions_phase
        CHECK (phase IN ('RESERVED', 'STARTING', 'RUNNING', 'STOPPING', 'RELEASED')),

    CONSTRAINT ck_executions_stop_cause
        CHECK (stop_cause IN ('STOP_REQUESTED', 'FAILURE', 'INTERRUPTION')),

    CONSTRAINT ck_executions_outcome
        CHECK (outcome IN ('COMPLETED', 'FAILED', 'INTERRUPTED')),

    -- Only a released execution has an outcome and a release time.
    CONSTRAINT ck_executions_released
        CHECK ((phase = 'RELEASED') = (released_at IS NOT NULL AND outcome IS NOT NULL))
);

-- The local instance runs at most one execution at a time, across all users (US079).
-- An execution holds the reservation until its cleanup ends.
CREATE UNIQUE INDEX ux_executions_single_active
    ON executions ((TRUE))
    WHERE released_at IS NULL;

CREATE INDEX ix_executions_scenario
    ON executions (scenario_id, created_at DESC);

-- The historical identity of each node inside an execution. Metrics will point here, not to the editable node.
CREATE TABLE executed_components (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    execution_id BIGINT NOT NULL,
    component_key UUID NOT NULL,
    name VARCHAR(30) NOT NULL,
    type VARCHAR(50) NOT NULL,
    contract_version INTEGER NOT NULL,
    profile VARCHAR(50) NOT NULL,
    parameters JSONB NOT NULL,

    CONSTRAINT pk_executed_components
        PRIMARY KEY (id),

    CONSTRAINT fk_executed_components_execution
        FOREIGN KEY (execution_id) REFERENCES executions (id) ON DELETE CASCADE,

    CONSTRAINT uk_executed_components_execution_key
        UNIQUE (execution_id, component_key),

    CONSTRAINT ck_executed_components_type
        CHECK (type IN ('HTTP_SERVICE', 'WORKER', 'POSTGRESQL', 'REDIS', 'RABBITMQ')),

    CONSTRAINT ck_executed_components_parameters_object
        CHECK (jsonb_typeof(parameters) = 'object')
);

-- The frozen connections, between executed nodes of the same execution.
CREATE TABLE executed_connections (
    execution_id BIGINT NOT NULL,
    source_key UUID NOT NULL,
    port VARCHAR(50) NOT NULL,
    target_key UUID NOT NULL,

    CONSTRAINT pk_executed_connections
        PRIMARY KEY (execution_id, source_key, port, target_key),

    CONSTRAINT fk_executed_connections_source
        FOREIGN KEY (execution_id, source_key)
            REFERENCES executed_components (execution_id, component_key) ON DELETE CASCADE,

    CONSTRAINT fk_executed_connections_target
        FOREIGN KEY (execution_id, target_key)
            REFERENCES executed_components (execution_id, component_key) ON DELETE CASCADE
);
