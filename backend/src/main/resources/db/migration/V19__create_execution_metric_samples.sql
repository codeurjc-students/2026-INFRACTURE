-- CPU and memory of each executed node over time (#93). A sample points to the frozen node, so editing
-- the canvas does not change the history. An empty value means Docker gave no reading, which is not zero.
CREATE TABLE execution_metric_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    executed_component_id BIGINT NOT NULL,
    sampled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    cpu_percent DOUBLE PRECISION,
    memory_bytes BIGINT,

    CONSTRAINT pk_execution_metric_samples
        PRIMARY KEY (id),

    CONSTRAINT fk_execution_metric_samples_component
        FOREIGN KEY (executed_component_id) REFERENCES executed_components (id) ON DELETE CASCADE,

    CONSTRAINT ck_execution_metric_samples_cpu
        CHECK (cpu_percent >= 0),

    CONSTRAINT ck_execution_metric_samples_memory
        CHECK (memory_bytes >= 0)
);

-- One node's series, in order and from a cursor.
CREATE INDEX ix_execution_metric_samples_component
    ON execution_metric_samples (executed_component_id, id);
