-- What happened during an execution (#92): node states, lifecycle events and summarized log lines.
-- The id grows with every row, so it orders the events and is the cursor a reconnecting client resumes from.
CREATE TABLE execution_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    execution_id BIGINT NOT NULL,
    -- Null when the event belongs to the whole execution, or to its load.
    component_key UUID,
    kind VARCHAR(10) NOT NULL,
    at TIMESTAMP WITH TIME ZONE NOT NULL,
    payload JSONB NOT NULL,

    CONSTRAINT pk_execution_events
        PRIMARY KEY (id),

    CONSTRAINT fk_execution_events_execution
        FOREIGN KEY (execution_id) REFERENCES executions (id) ON DELETE CASCADE,

    CONSTRAINT ck_execution_events_kind
        CHECK (kind IN ('STATE', 'EVENT', 'LOG')),

    CONSTRAINT ck_execution_events_payload_object
        CHECK (jsonb_typeof(payload) = 'object')
);

CREATE INDEX ix_execution_events_execution
    ON execution_events (execution_id, id);
