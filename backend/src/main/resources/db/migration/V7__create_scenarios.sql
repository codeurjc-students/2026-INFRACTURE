CREATE TABLE scenarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    project_id BIGINT NOT NULL,
    name VARCHAR(30) NOT NULL,
    description VARCHAR(280),
    revision INTEGER NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT pk_scenarios
        PRIMARY KEY (id),

    CONSTRAINT fk_scenarios_project
        FOREIGN KEY (project_id) REFERENCES projects (id),

    CONSTRAINT ck_scenarios_name_not_blank
        CHECK (BTRIM(name) <> ''),

    CONSTRAINT ck_scenarios_revision_positive
        CHECK (revision >= 1)
);

CREATE INDEX ix_scenarios_project_created
    ON scenarios (project_id, created_at DESC, id DESC);
