CREATE TABLE components (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    scenario_id BIGINT NOT NULL,
    component_key UUID NOT NULL,
    template_key VARCHAR(50) NOT NULL,
    type VARCHAR(50) NOT NULL,
    name VARCHAR(30) NOT NULL,
    position_x DOUBLE PRECISION NOT NULL,
    position_y DOUBLE PRECISION NOT NULL,
    profile VARCHAR(50),
    parameters JSONB NOT NULL,

    CONSTRAINT pk_components
        PRIMARY KEY (id),

    CONSTRAINT fk_components_scenario
        FOREIGN KEY (scenario_id) REFERENCES scenarios (id) ON DELETE CASCADE,

    CONSTRAINT fk_components_template
        FOREIGN KEY (template_key) REFERENCES component_template (template_key),

    CONSTRAINT uk_components_scenario_key
        UNIQUE (scenario_id, component_key),

    CONSTRAINT ck_components_type
        CHECK (
            type IN (
                'HTTP_SERVICE',
                'WORKER',
                'POSTGRESQL',
                'REDIS',
                'RABBITMQ'
            )
        ),

    CONSTRAINT ck_components_name_not_blank
        CHECK (BTRIM(name) <> ''),

    CONSTRAINT ck_components_parameters_object
        CHECK (jsonb_typeof(parameters) = 'object')
);

DELETE FROM component_template
WHERE type = 'LOAD_GENERATOR';

ALTER TABLE component_template
    DROP CONSTRAINT ck_component_template_type,
    ADD CONSTRAINT ck_component_template_type
        CHECK (
            type IN (
                'HTTP_SERVICE',
                'WORKER',
                'POSTGRESQL',
                'REDIS',
                'RABBITMQ'
            )
        ),
    ADD COLUMN initial_configuration JSONB;

UPDATE component_template
SET initial_configuration = CASE type
    WHEN 'HTTP_SERVICE' THEN '{"profile": "STATELESS", "parameters": {"responseDelayMs": 0}}'::jsonb
    WHEN 'WORKER' THEN '{"profile": "CONSUMER", "parameters": {}}'::jsonb
    ELSE '{"profile": "DEFAULT", "parameters": {}}'::jsonb
END;

ALTER TABLE component_template
    ALTER COLUMN initial_configuration SET NOT NULL,
    ADD CONSTRAINT ck_component_template_initial_configuration_object
        CHECK (jsonb_typeof(initial_configuration) = 'object');
